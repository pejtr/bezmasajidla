export interface Restaurant {
  id: string;
  name: string;
  slug: string;
  type: RestaurantType;
  rating: number;
  reviewCount: number;
  isOpen: boolean;
  isPremium: boolean;
  address: string;
  district: string;
  phone?: string;
  website?: string;
  description: string;
  tags: string[];
  dietaryOptions: DietaryOption[];
  image: string;
  lat: number;
  lng: number;
  priceLevel: 1 | 2 | 3;
  hours?: string;
  shoppingCenter?: string;
  /** Vegetarian/vegan menu items for fast food chains */
  fastFoodItems?: FastFoodItem[];
  /** Direct Wolt delivery URL for this restaurant */
  woltUrl?: string;
  /** Additional photo gallery images */
  gallery?: string[];
  /** Instagram profile URL */
  instagramUrl?: string;
  /** Facebook page URL */
  facebookUrl?: string;
  /** Editorial review by the Bezmasá Jídla team */
  editorialReview?: {
    /** Overall editorial score out of 10 */
    score: number;
    /** One-sentence summary of the restaurant */
    summary: string;
    /** Who is this restaurant best suited for */
    bestFor: string;
    /** The must-order dishes */
    mustOrder: string[];
    /** What to skip or be cautious about */
    skip?: string;
    /** Full editorial text (2-3 paragraphs) */
    body: string;
    /** Specific category scores (1-10) */
    scores: {
      food: number;
      value: number;
      atmosphere: number;
      service: number;
    };
  };
}

